const ORDER: SocialPlatform[] = [
  "whatsapp",
  "instagram",
  "facebook",
  "linkedin",
  "twitter",
  "youtube",
  "tiktok",
];

export function SocialBadges({ social }: { social?: SocialLinks }) {
  const entries = ORDER.filter((platform) => social?.[platform]);
  if (entries.length === 0) return <span className="text-xs text-slate-600">—</span>;

  return (
    <div className="flex flex-wrap items-center gap-1.5">
      {entries.map((platform) => {
        const { label, color, path } = PLATFORMS[platform];
        const href = social?.[platform] ?? "";
        return (
          <a
            key={platform}
            href={href}
            target="_blank"
            rel="noopener noreferrer"
            onClick={(e) => e.stopPropagation()}
            title={label}
            aria-label={`${label} de la empresa`}
            className="inline-flex h-7 w-7 items-center justify-center rounded-lg border border-slate-700 bg-slate-900/70 transition hover:border-slate-500 hover:bg-slate-800"
            style={{ color }}
          >
            <svg viewBox="0 0 24 24" className="h-4 w-4" fill="currentColor" aria-hidden="true">
              <path d={path} />
            </svg>
          </a>
        );
      })}
    </div>
  );
}
